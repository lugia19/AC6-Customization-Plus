//! WEAPON VFX: the player's melee weapons in colors of their own, saved with the AC.
//! The weapons are tools/weapons.py's WEAPONS; what they play and their materials' parameters come from the game's data
//! (the build writes weapon_table.rs).
//! - Effects: each weapon effect has a replace row whose custom columns (the player's only: columns.rs's color type
//!   hook) play a copy tinted by external values: a weapon's color on a block from EXT_BASE + EXT_BLOCK * its model
//!   (ext_values.rs). Its hit effects: hits.rs.
//! - Colored materials of the part (blades, emissives): the player's AC loads a copy
//!   of the part, the model number's leading digit d -> 9 - d (0221 -> 9221, 1210 -> 8210), whose colored materials
//!   are its own copies. Hooks: the AC parts loader 0x1410d8460 notes whether the player's parts object is loading (a
//!   thread-local: the name builder runs inside it), the part name builder 0x1415d0080 then renames. The copied
//!   materials are found by name in the game's
//!   material repository (MtdRepository) and their colors set like the game's own matbin reload does: the value, then a
//!   commit that rebuilds the material's constant buffer.
//! Colors: the WEAPON VFX row (rows.rs), saved with the AC: every melee weapon has its own color in the row's section
//! (WEAPONS' order: colors 0-5, then pattern colors 0-3; docs/storage.md), and the panel shows the two equipped
//! ones: the left-arm melee weapon and the left-back one (melee weapons go nowhere else). A weapon without a color
//! keeps its stock blade, and its effects get the weapon's default color. On the row the preview flashes the weapons'
//! units, in the panel the hovered entry's (the highlight hook 0x14102c4c0).

use std::cell::Cell;
use std::collections::BTreeMap;
use std::sync::atomic::AtomicUsize;

use crate::ext_values::{self, Block, Channels};
use crate::game::{self, CHR_PARTS_OFFSET, SLOT_LEFT_ARM, SLOT_LEFT_BACK, game_fn, utf16};
use crate::rows::{self, ROW_WEAPONS};
use crate::{Hook, log, orig};

struct Weapon {
    /// Its EquipParamWeapon row (what the assembly holds).
    id: i32,
    model: u16,
    /// What its effects get until a color is set.
    default: u32,
    /// Its BehaviorParam variation (behaviorVariationId): its attacks' and bullets' IDs / 1000.
    variation: i32,
    /// Its colored materials' copies (tools/weapons.py player_copy).
    materials: &'static [Material],
    /// The hit effects it makes, which have copies (hits.rs).
    hits: &'static [i32],
}

/// A material's name and its color parameters.
struct Material {
    name: &'static [u16],
    colors: &'static [&'static [u16]],
}

// The weapons (in their colors' saved order), their hit effects and their materials' copies with their color parameters,
// and the IDs the build and the DLL share: generated by build.py from the game's data (tools/weapons.py WEAPONS).
include!("weapon_table.rs");

// A color parameter's rgba (then its intensity).
const PARAM_VALUE_OFFSET: usize = 0x40;

// The panel's entries: the left-arm weapon's color, the left-back one's.
const SLOTS: [usize; 2] = [SLOT_LEFT_ARM, SLOT_LEFT_BACK];
// Where weapon i's color is in the row's section: the six colors, then the four pattern colors (no part uses them).
const SECTION_COLORS_OFFSET: usize = 0x8;
const SECTION_PATTERN_COLORS_OFFSET: usize = 0x30;
const _: () = assert!(WEAPONS.len() <= 10, "the row's section has room for ten weapons' colors");
// The panel's labels: the weapons' names from the game's text (MsgRepository: `const wchar_t* text(repository,
// category, id, fallback)`; category 11, the item text's weapon names, by EquipParamWeapon ID).
const MSG_REPOSITORY_ADDR: usize = 0x144e256d8;
const TEXT_ADDR: usize = 0x14157d750;
const WEAPON_NAMES: i16 = 11;
static NO_WEAPON: [u16; 20] = utf16(b"No supported weapon\0");

const MTD_REPOSITORY_ADDR: usize = 0x144e1cc38;
// `MtdResCap* find(repository, const wchar_t* name)`; the material at rescap + 0x78.
const FIND_MATERIAL_ADDR: usize = 0x141344fe0;
const RESCAP_MATERIAL_OFFSET: usize = 0x78;
// `param* find_param(material, const wchar_t* name)`, `void commit(material)`.
const FIND_PARAM_ADDR: usize = 0x142300730;
const COMMIT_ADDR: usize = 0x1423020a0;
// The name builder's output, an FD4 wide string: +8 the characters (inline up to 7, else a pointer there), +0x18 the
// length, +0x20 the capacity.
const STRING_LENGTH_OFFSET: usize = 0x18;
const STRING_CAPACITY_OFFSET: usize = 0x20;

type FindFn = unsafe extern "system" fn(usize, *const u16) -> usize;
type CommitFn = unsafe extern "system" fn(usize);
type LoaderFn = unsafe extern "system" fn(usize, usize, usize, usize, usize, usize, usize, usize, usize) -> usize;
type PartNameFn = unsafe extern "system" fn(usize, usize, usize, usize, usize) -> usize;

static ORIG_LOADER: AtomicUsize = AtomicUsize::new(0);
static ORIG_PART_NAME: AtomicUsize = AtomicUsize::new(0);
static CHANNELS: [Channels; WEAPONS.len()] = [const { ext_values::unset() }; WEAPONS.len()];

thread_local! {
    // Whether the AC parts loader is loading the player's parts, while it runs.
    static LOADING_PLAYERS: Cell<bool> = const { Cell::new(false) };
}

pub(crate) fn hooks() -> [Hook; 3] {
    [
        // push rbp / push rsi / push rdi / push r12
        (0x1410d8460, [0x40, 0x55, 0x56, 0x57, 0x41, 0x54], loader_impl as *const (), &ORIG_LOADER),
        // mov [rsp+8],rbx / mov [rsp+10],rbp
        (0x1415d0080, [0x48, 0x89, 0x5c, 0x24, 0x08, 0x48], part_name_impl as *const (), &ORIG_PART_NAME),
        // mov [rsp+8],rbx / push rdi
        (0x14102c4c0, [0x48, 0x89, 0x5c, 0x24, 0x08, 0x57], highlight_entry as *const (), &ORIG_HIGHLIGHT),
    ]
}

// The Paint screen's highlight (the parts flashing orange): 0x14102c4c0(model view, &sections, &color slots, filter),
// spans {begin, end} of u8, kept by pointer (a new span restarts the flash). Every frame: the category's sections and
// the current row's slots, none for our rows. On WEAPON VFX the weapons' units flash instead (sections: left arm unit
// 8, left back unit 13; SLOTS' order), all slots: both on the row, the entry's in its panel.
type HighlightFn = unsafe extern "system" fn(usize, *const [*const u8; 2], *const [*const u8; 2], i32);
static ORIG_HIGHLIGHT: AtomicUsize = AtomicUsize::new(0);
// The call that matters: the Paint screen's update (0x140f4e610), past its category list (that call returns to
// 0x140f4e814). The entry stub keeps the return address (the main thread's; the only caller).
const PAINT_HIGHLIGHT_RETURN: usize = 0x140f4e86e;
static HIGHLIGHT_CALLER: AtomicUsize = AtomicUsize::new(0);

#[unsafe(naked)]
unsafe extern "system" fn highlight_entry() {
    std::arch::naked_asm!(
        "mov rax, [rsp]",
        "mov [rip + {caller}], rax",
        "jmp {body}",
        caller = sym HIGHLIGHT_CALLER,
        body = sym highlight_impl,
    );
}
static UNIT_SECTIONS: [u8; 2] = [8, 13];
static ALL_SLOTS: [u8; 6] = [0, 1, 2, 3, 4, 5];

unsafe extern "system" fn highlight_impl(view: usize, sections: *const [*const u8; 2], slots: *const [*const u8; 2],
                                         filter: i32) {
    let highlight = unsafe { orig::<HighlightFn>(&ORIG_HIGHLIGHT) };
    let caller = HIGHLIGHT_CALLER.load(std::sync::atomic::Ordering::Relaxed);
    let cursor = if caller == PAINT_HIGHLIGHT_RETURN { crate::panel::cursor() } else { None };
    let units = match cursor {
        Some((kind, entry)) if rows::row_of_kind(kind) == Some(ROW_WEAPONS) => match entry {
            Some(which) => UNIT_SECTIONS.get(which..which + 1),
            None => Some(&UNIT_SECTIONS[..]),
        },
        _ => None,
    };
    let Some(units) = units else { return unsafe { highlight(view, sections, slots, filter) } };
    let span = |s: &'static [u8]| [s.as_ptr(), s.as_ptr_range().end];
    unsafe { highlight(view, &span(units), &span(&ALL_SLOTS), filter) }
}

unsafe extern "system" fn loader_impl(parts: usize, a2: usize, a3: usize, a4: usize, a5: usize, a6: usize, a7: usize,
                                      a8: usize, a9: usize) -> usize {
    let players = game::player().and_then(|player| game::read::<usize>(player + CHR_PARTS_OFFSET)) == Some(parts);
    let outer = LOADING_PLAYERS.replace(players);
    let result = unsafe { orig::<LoaderFn>(&ORIG_LOADER)(parts, a2, a3, a4, a5, a6, a7, a8, a9) };
    LOADING_PLAYERS.set(outer);
    result
}

/// Builds a part's name ("WP_L_0221", "WP_L_0221_L"...); the player's parts with colored materials get their copy's
/// (the number's leading digit d -> 9 - d).
unsafe extern "system" fn part_name_impl(out: usize, row: usize, a3: usize, a4: usize, a5: usize) -> usize {
    let result = unsafe { orig::<PartNameFn>(&ORIG_PART_NAME)(out, row, a3, a4, a5) };
    if LOADING_PLAYERS.get() {
        rename_part(out);
    }
    result
}

fn rename_part(string: usize) -> Option<()> {
    let length = game::read::<usize>(string + STRING_LENGTH_OFFSET)?;
    let inline = game::read::<usize>(string + STRING_CAPACITY_OFFSET)? <= 7;
    let at = if inline { string + 8 } else { game::read::<usize>(string + 8)? };
    let chars = game::read::<[u16; 10]>(at)?;
    let ends = length == 9 || length > 9 && chars[9] == u16::from(b'_');
    let model: u16 = String::from_utf16(&chars[5..9]).ok()?.parse().ok()?;
    if chars[..5] != utf16(b"WP_L_") || !ends || !WEAPONS.iter().any(|w| w.model == model && !w.materials.is_empty()) {
        return None;
    }
    unsafe { *((at + 5 * 2) as *mut u16) = u16::from(b'9') - (chars[5] - u16::from(b'0')) };
    Some(())
}

pub(crate) fn ext_blocks() -> impl Iterator<Item = Block> {
    WEAPONS.iter().zip(&CHANNELS).map(|(weapon, channels)| Block { first: EXT_BASE + EXT_BLOCK * i32::from(weapon.model), channels })
}

/// A copied material in the game's repository, and its color parameters with their stock rgb.
struct Found {
    material: usize,
    params: Vec<(usize, [f32; 3])>,
}

fn find_material(material: &Material) -> Option<Found> {
    let repository = game::read::<usize>(MTD_REPOSITORY_ADDR).filter(|&r| r != 0)?;
    let rescap = Some(unsafe { game_fn::<FindFn>(FIND_MATERIAL_ADDR)(repository, material.name.as_ptr()) })
        .filter(|&r| r != 0)?;
    let address = game::read::<usize>(rescap + RESCAP_MATERIAL_OFFSET).filter(|&m| m != 0)?;
    let find_param: FindFn = unsafe { game_fn(FIND_PARAM_ADDR) };
    let params = material.colors.iter().filter_map(|color| {
        let param = Some(unsafe { find_param(address, color.as_ptr()) }).filter(|&p| p != 0)?;
        Some((param, game::read::<[f32; 3]>(param + PARAM_VALUE_OFFSET)?))
    });
    Some(Found { material: address, params: params.collect() })
}

/// Each color takes the chosen color, at its stock brightness (its brightest channel); stock without one.
fn paint(found: &Found, rgb: Option<u32>) {
    for &(param, stock) in &found.params {
        let value = rgb.map_or(stock, |rgb| {
            let brightest = stock.iter().copied().fold(0.0, f32::max);
            ext_values::channels(rgb).map(|c| c * brightest)
        });
        unsafe { *((param + PARAM_VALUE_OFFSET) as *mut [f32; 3]) = value };
    }
    unsafe { game_fn::<CommitFn>(COMMIT_ADDR)(found.material) };
}

/// The copy (its bundle) of a hit effect for the weapon of a BehaviorParam variation, if it has one.
pub(crate) fn hit_copy(variation: i32, sfx: i32) -> Option<i32> {
    let weapon = WEAPONS.iter().find(|w| w.variation == variation && w.hits.contains(&sfx))?;
    Some(sfx + i32::from(weapon.model) * HIT_MODEL_STRIDE + HIT_BUNDLE_OFFSET)
}

fn equipped(slot: usize) -> Option<&'static Weapon> {
    equipped_index(slot).map(|weapon| &WEAPONS[weapon])
}

/// The game's name for a weapon (its text stays loaded), with the terminator.
fn weapon_name(id: i32) -> Option<&'static [u16]> {
    let repository = game::read::<usize>(MSG_REPOSITORY_ADDR).filter(|&r| r != 0)?;
    let text: unsafe extern "system" fn(usize, i16, i32, usize) -> usize = unsafe { game_fn(TEXT_ADDR) };
    let at = Some(unsafe { text(repository, WEAPON_NAMES, id, 0) }).filter(|&t| t != 0)?;
    let length = (0..64).find(|&i| game::read::<u16>(at + i * 2) == Some(0))?;
    Some(unsafe { std::slice::from_raw_parts(at as *const u16, length + 1) })
}

/// A color's label in the panel: the name of the melee weapon in its slot.
fn label(which: usize) -> &'static [u16] {
    equipped(SLOTS[which]).and_then(|weapon| weapon_name(weapon.id)).unwrap_or(&NO_WEAPON)
}

fn storage_offset(weapon: usize) -> usize {
    match weapon {
        0..6 => SECTION_COLORS_OFFSET + weapon * 4,
        _ => SECTION_PATTERN_COLORS_OFFSET + (weapon - 6) * 4,
    }
}

/// The equipped melee weapon of a slot, as its index in WEAPONS.
fn equipped_index(slot: usize) -> Option<usize> {
    let id = game::player_weapon(slot)?;
    WEAPONS.iter().position(|w| w.id == id)
}

/// The panel's entry `which`: the color of the weapon equipped in its slot.
fn slot(which: usize) -> Option<rows::Slot> {
    let weapon = equipped_index(SLOTS[which])?;
    Some(rows::Slot { offset: storage_offset(weapon), default: WEAPONS[weapon].default })
}

pub(crate) fn claim_row() {
    rows::claim_dynamic(ROW_WEAPONS, "WEAPON VFX", SLOTS.len(), label, slot);
}

/// The colors picked for the player's equipped melee weapons, by model.
fn current_colors() -> BTreeMap<u16, u32> {
    SLOTS.iter()
        .filter_map(|&slot| {
            let weapon = equipped_index(slot)?;
            Some((WEAPONS[weapon].model, rows::picked_at(ROW_WEAPONS, storage_offset(weapon))?))
        })
        .collect()
}

/// What was last applied, for the update loop (lib.rs).
pub(crate) struct Weapons {
    // The weapons' materials, once found (they load at boot), in WEAPONS' and their materials' order.
    materials: Vec<Option<Found>>,
    colors: Option<BTreeMap<u16, u32>>,
}

impl Weapons {
    pub(crate) fn new() -> Self {
        Weapons { materials: WEAPONS.iter().flat_map(|w| w.materials).map(|_| None).collect(), colors: None }
    }

    /// Applies the colors when they change, and to each material when it's found.
    pub(crate) fn update(&mut self) {
        let now = current_colors();
        let changed = self.colors.as_ref() != Some(&now);
        if changed {
            let listed: Vec<String> = now.iter().map(|(model, color)| format!("{model} #{color:06X}")).collect();
            log(&format!("weapons: colors {}", listed.join(", ")));
            for (weapon, channels) in WEAPONS.iter().zip(&CHANNELS) {
                ext_values::set_channels(channels, now.get(&weapon.model).copied().unwrap_or(weapon.default));
            }
        }
        let materials = WEAPONS.iter().flat_map(|w| w.materials.iter().map(move |m| (w, m)));
        for ((weapon, material), slot) in materials.zip(&mut self.materials) {
            let color = now.get(&weapon.model).copied();
            if slot.is_none() {
                *slot = find_material(material);
                if let Some(found) = slot {
                    log(&format!("weapons: material of {} at {:#x}, {} colors", weapon.model, found.material,
                                 found.params.len()));
                    paint(found, color);
                }
            } else if changed {
                paint(slot.as_ref().unwrap(), color);
            }
        }
        self.colors = Some(now);
    }
}
