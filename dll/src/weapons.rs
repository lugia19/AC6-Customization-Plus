//! WEAPON VFX: the player's melee weapons in colors of their own, saved with the AC.
//! The weapons are tools/weapons.py's WEAPONS; what they play and their materials' parameters come from the game's data
//! (the build writes weapon_table.rs).
//! - Effects: each weapon effect has a replace row whose custom columns (the player's only: columns.rs's color type
//!   hook) play a copy tinted by external values: a weapon's color on a block from EXT_BASE + EXT_BLOCK * its model
//!   (ext_values.rs). Its hit effects: hits.rs.
//! - Colored materials of the part (blades, emissives): entries in the player's weapon models' material param
//!   modifiers, under names whose keys the build gave the params in their shaders (docs/material-overrides.md), added
//!   when the game paints a model (hook 0x1410ff770).
//! Colors: the WEAPON VFX row (rows.rs), saved with the AC: every melee weapon has its own color in a paint section no
//! part uses (WEAPONS' order: section 9's ten color fields, then section 6's; docs/storage.md), and the panel shows the
//! two equipped ones: the left-arm melee weapon and the left-back one (melee weapons go nowhere else). A weapon
//! without a color keeps its stock blade, and its effects get the weapon's default color. The panel's third entry is
//! the core expansion's effects' color (one for every expansion; its effects are replace rows too). On the row the
//! preview flashes the weapons' units, in the panel the hovered weapon's (the highlight hook 0x14102c4c0).

use std::collections::BTreeMap;
use std::sync::atomic::AtomicUsize;

use crate::ext_values::{self, Block, Channels};
use crate::game::{self, CHR_MODEL_OFFSET, SLOT_LEFT_ARM, SLOT_LEFT_BACK, game_fn, utf16};
use crate::rows::{self, ROW_WEAPONS};
use crate::{Hook, log, orig};

struct Weapon {
    /// Its EquipParamWeapon row (what the assembly holds).
    id: i32,
    model: u16,
    /// What its effects get until a color is set.
    default: u32,
    /// Its BehaviorParam variation (behaviorVariationId): its attacks' and bullets' IDs / 1000.
    variation: i32,
    /// Its materials' color params, as its model's entries for them.
    colors: &'static [Color],
    /// The hit effects it makes, which have copies (hits.rs).
    hits: &'static [i32],
}

/// A color param's entry: its name (its hash is the param's key in its shader), and the param's stock value.
struct Color {
    name: &'static [u16],
    rgba: [f32; 4],
    intensity: f32,
}

// The weapons (in their colors' saved order), their hit effects and their materials' colors, and the IDs the build and
// the DLL share: generated by build.py from the game's data (tools/weapons.py WEAPONS).
include!("weapon_table.rs");

// The panel's entries, the left-arm weapon's color and the left-back one's: the weapon's assembly slot, its parts slot
// (the AC model object's model list) and its unit's paint section.
struct WeaponSlot {
    assembly: usize,
    parts: usize,
    section: u8,
}
const SLOTS: [WeaponSlot; 2] = [
    WeaponSlot { assembly: SLOT_LEFT_ARM, parts: 6, section: 8 },
    WeaponSlot { assembly: SLOT_LEFT_BACK, parts: 7, section: 13 },
];
// The third entry: the expansion color, one for every expansion (rows::EXPANSION_COLOR_FIELD), served on 900021 on; the
// preview flashes nothing for it.
const EXPANSION_ENTRY: usize = SLOTS.len();
const EXPANSION_EXT_FIRST: i32 = 900021;
const EXPANSION_DEFAULT: u32 = 0xFFFFFF;
static UNIT_SECTIONS: [u8; 2] = [SLOTS[0].section, SLOTS[1].section];
static EXPANSION_LABEL: [u16; 16] = utf16(b"Expansion color\0");
static EXPANSION_CHANNELS: Channels = ext_values::unset();

// The AC model object: a model list per parts slot, {+8 up to 16 part models, +0x88 i32 count}. A part model: +0x10 its
// model item, whose +0x50 is its material param modifier component, +8 the GXMaterialParamModifier.
const MODEL_LISTS_OFFSET: usize = 0xa8;
const LIST_COUNT_OFFSET: usize = 0x88;
const LIST_CAPACITY: i32 = 16;
const MODEL_ITEM_OFFSET: usize = 0x10;
const ITEM_COMPONENT_OFFSET: usize = 0x50;
const COMPONENT_MODIFIER_OFFSET: usize = 8;
// `void set(modifier, i32 material id (0: all), const wchar_t* param, const f32 values[5], f32 blend)`: adds an entry,
// or updates the one with the same param and id. Values: rgb, alpha, intensity.
const SET_ENTRY_ADDR: usize = 0x1423ebdc0;
// Where the weapons' colors are, in WEAPONS' order: the color fields (rows::color_field) of these sections.
const STORAGE_SECTIONS: [usize; 2] = [9, 6];
const FIELDS_PER_SECTION: usize = 10;
const _: () = assert!(WEAPONS.len() <= STORAGE_SECTIONS.len() * FIELDS_PER_SECTION, "no room for the weapons' colors");
// The panel's labels: the weapons' names from the game's text (MsgRepository: `const wchar_t* text(repository,
// category, id, fallback)`; category 11, the item text's weapon names, by EquipParamWeapon ID).
const MSG_REPOSITORY_ADDR: usize = 0x144e256d8;
const TEXT_ADDR: usize = 0x14157d750;
const WEAPON_NAMES: i16 = 11;
static NO_WEAPON: [u16; 20] = utf16(b"No supported weapon\0");

type SetEntryFn = unsafe extern "system" fn(usize, i32, *const u16, *const f32, f32);
// `paint_model(part model, u8 paint section, paint section data)`: paints one model when it's built or repainted.
type PaintModelFn = unsafe extern "system" fn(usize, usize, usize, usize) -> usize;

static ORIG_PAINT_MODEL: AtomicUsize = AtomicUsize::new(0);
static CHANNELS: [Channels; WEAPONS.len()] = [const { ext_values::unset() }; WEAPONS.len()];

pub(crate) fn hooks() -> [Hook; 2] {
    [
        // mov rax,rsp / mov [rax+10],dl
        (0x1410ff770, [0x48, 0x8b, 0xc4, 0x88, 0x50, 0x10], paint_model_impl as *const (), &ORIG_PAINT_MODEL),
        // mov [rsp+8],rbx / push rdi
        (0x14102c4c0, [0x48, 0x89, 0x5c, 0x24, 0x08, 0x57], highlight_entry as *const (), &ORIG_HIGHLIGHT),
    ]
}

// The Paint screen's highlight (the parts flashing orange): 0x14102c4c0(model view, &sections, &color slots, filter),
// spans {begin, end} of u8, kept by pointer (a new span restarts the flash). Every frame: the category's sections and
// the current row's slots, none for our rows. On WEAPON VFX the weapons' units flash instead (sections: left arm unit
// SLOTS' sections), all slots: both on the row, the entry's in its panel.
type HighlightFn = unsafe extern "system" fn(usize, *const [*const u8; 2], *const [*const u8; 2], i32);
static ORIG_HIGHLIGHT: AtomicUsize = AtomicUsize::new(0);
// The call that matters: the Paint screen's update (0x140f4e610), past its category list (that call returns to
// 0x140f4e814). The entry stub keeps the return address (the main thread's; the only caller).
const PAINT_HIGHLIGHT_RETURN: usize = 0x140f4e86e;
static HIGHLIGHT_CALLER: AtomicUsize = AtomicUsize::new(0);

#[unsafe(naked)]
unsafe extern "system" fn highlight_entry() {
    std::arch::naked_asm!(
        "mov rax, [rsp]",
        "mov [rip + {caller}], rax",
        "jmp {body}",
        caller = sym HIGHLIGHT_CALLER,
        body = sym highlight_impl,
    );
}
static ALL_SLOTS: [u8; 6] = [0, 1, 2, 3, 4, 5];

unsafe extern "system" fn highlight_impl(view: usize, sections: *const [*const u8; 2], slots: *const [*const u8; 2],
                                         filter: i32) {
    let highlight = unsafe { orig::<HighlightFn>(&ORIG_HIGHLIGHT) };
    let caller = HIGHLIGHT_CALLER.load(std::sync::atomic::Ordering::Relaxed);
    let cursor = if caller == PAINT_HIGHLIGHT_RETURN { crate::panel::cursor() } else { None };
    let units = match cursor {
        Some((kind, entry)) if rows::row_of_kind(kind) == Some(ROW_WEAPONS) => match entry {
            Some(which) => UNIT_SECTIONS.get(which..which + 1),
            None => Some(&UNIT_SECTIONS[..]),
        },
        _ => None,
    };
    let Some(units) = units else { return unsafe { highlight(view, sections, slots, filter) } };
    let span = |s: &'static [u8]| [s.as_ptr(), s.as_ptr_range().end];
    unsafe { highlight(view, &span(units), &span(&ALL_SLOTS), filter) }
}

/// Paints a part model; one of the player's weapons' then gets its colors' entries.
unsafe extern "system" fn paint_model_impl(model: usize, section: usize, section_data: usize, a4: usize) -> usize {
    let result = unsafe { orig::<PaintModelFn>(&ORIG_PAINT_MODEL)(model, section, section_data, a4) };
    if let Some(which) = SLOTS.iter().position(|s| usize::from(s.section) == section & 0xff)
        && let Some(weapon) = equipped_index(SLOTS[which].assembly)
        && !WEAPONS[weapon].colors.is_empty()
        && is_players_model(which, model)
        && let Some(modifier) = modifier(model)
    {
        let set: SetEntryFn = unsafe { game_fn(SET_ENTRY_ADDR) };
        let picked = rows::picked_at(storage_offset(weapon));
        for color in WEAPONS[weapon].colors {
            unsafe { set(modifier, 0, color.name.as_ptr(), paint(color, picked).as_ptr(), 1.0) };
        }
    }
    result
}

/// Whether a part model is in the player's model list of a weapon's parts slot (SLOTS' order).
fn is_players_model(which: usize, model: usize) -> bool {
    let list = game::player()
        .and_then(|player| game::read::<usize>(player + CHR_MODEL_OFFSET).filter(|&o| o != 0))
        .and_then(|owner| game::read::<usize>(owner + MODEL_LISTS_OFFSET + SLOTS[which].parts * 8).filter(|&l| l != 0));
    let Some(list) = list else { return false };
    let count = game::read::<i32>(list + LIST_COUNT_OFFSET).unwrap_or(0).clamp(0, LIST_CAPACITY) as usize;
    (0..count).any(|i| game::read::<usize>(list + 8 + i * 8) == Some(model))
}

/// A part model's material param modifier.
fn modifier(model: usize) -> Option<usize> {
    let item = game::read::<usize>(model + MODEL_ITEM_OFFSET).filter(|&i| i != 0)?;
    let component = game::read::<usize>(item + ITEM_COMPONENT_OFFSET).filter(|&c| c != 0)?;
    Some(component + COMPONENT_MODIFIER_OFFSET)
}

pub(crate) fn ext_blocks() -> impl Iterator<Item = Block> {
    WEAPONS.iter()
        .zip(&CHANNELS)
        .map(|(weapon, channels)| Block { first: EXT_BASE + EXT_BLOCK * i32::from(weapon.model), channels })
        .chain(std::iter::once(Block { first: EXPANSION_EXT_FIRST, channels: &EXPANSION_CHANNELS }))
}

/// A color param's entry values: the chosen color, as white as the stock one is (its saturation: the blade needs its
/// pale layers pale), at its stock brightness (its brightest channel); stock without one.
fn paint(color: &Color, picked: Option<u32>) -> [f32; 5] {
    let stock = [color.rgba[0], color.rgba[1], color.rgba[2]];
    let [r, g, b] = picked.map_or(stock, |rgb| {
        let brightest = stock.iter().copied().fold(0.0, f32::max);
        let palest = stock.iter().copied().fold(f32::INFINITY, f32::min);
        let saturation = if brightest > 0.0 { 1.0 - palest / brightest } else { 1.0 };
        ext_values::channels(rgb).map(|c| (1.0 - saturation + saturation * c) * brightest)
    });
    [r, g, b, color.rgba[3], color.intensity]
}

/// The copy (its bundle) of a hit effect for the weapon of a BehaviorParam variation, if it has one.
pub(crate) fn hit_copy(variation: i32, sfx: i32) -> Option<i32> {
    let weapon = WEAPONS.iter().find(|w| w.variation == variation && w.hits.contains(&sfx))?;
    Some(sfx + i32::from(weapon.model) * HIT_MODEL_STRIDE + HIT_BUNDLE_OFFSET)
}

fn equipped(slot: usize) -> Option<&'static Weapon> {
    equipped_index(slot).map(|weapon| &WEAPONS[weapon])
}

/// The game's name for a weapon (its text stays loaded), with the terminator.
fn weapon_name(id: i32) -> Option<&'static [u16]> {
    let repository = game::read::<usize>(MSG_REPOSITORY_ADDR).filter(|&r| r != 0)?;
    let text: unsafe extern "system" fn(usize, i16, i32, usize) -> usize = unsafe { game_fn(TEXT_ADDR) };
    let at = Some(unsafe { text(repository, WEAPON_NAMES, id, 0) }).filter(|&t| t != 0)?;
    let length = (0..64).find(|&i| game::read::<u16>(at + i * 2) == Some(0))?;
    Some(unsafe { std::slice::from_raw_parts(at as *const u16, length + 1) })
}

/// A color's label in the panel: the name of the melee weapon in its slot, or the expansion color's.
fn label(which: usize) -> &'static [u16] {
    if which == EXPANSION_ENTRY {
        return &EXPANSION_LABEL;
    }
    equipped(SLOTS[which].assembly).and_then(|weapon| weapon_name(weapon.id)).unwrap_or(&NO_WEAPON)
}

/// Where a weapon's color is in the paint block.
fn storage_offset(weapon: usize) -> usize {
    rows::color_field(STORAGE_SECTIONS[weapon / FIELDS_PER_SECTION], weapon % FIELDS_PER_SECTION)
}

/// The equipped melee weapon of a slot, as its index in WEAPONS.
fn equipped_index(slot: usize) -> Option<usize> {
    let id = game::player_weapon(slot)?;
    WEAPONS.iter().position(|w| w.id == id)
}

/// The expansion's color in the paint block.
fn expansion_offset() -> usize {
    rows::color_field(rows::EXPANSION_COLOR_FIELD.0, rows::EXPANSION_COLOR_FIELD.1)
}

/// The panel's entry `which`: the color of the weapon equipped in its slot, or the expansion color.
fn slot(which: usize) -> Option<rows::Slot> {
    if which == EXPANSION_ENTRY {
        return Some(rows::Slot { offset: expansion_offset(), default: EXPANSION_DEFAULT });
    }
    let weapon = equipped_index(SLOTS[which].assembly)?;
    Some(rows::Slot { offset: storage_offset(weapon), default: WEAPONS[weapon].default })
}

pub(crate) fn claim_row() {
    rows::claim_dynamic(ROW_WEAPONS, "WEAPON VFX", SLOTS.len() + 1, label, slot);
}

/// The colors picked for the player's equipped melee weapons, by model.
fn current_colors() -> BTreeMap<u16, u32> {
    SLOTS.iter()
        .filter_map(|slot| {
            let weapon = equipped_index(slot.assembly)?;
            Some((WEAPONS[weapon].model, rows::picked_at(storage_offset(weapon))?))
        })
        .collect()
}

/// What was last applied, for the update loop (lib.rs).
#[derive(Default)]
pub(crate) struct Weapons {
    colors: Option<BTreeMap<u16, u32>>,
    expansion: Option<u32>,
}

impl Weapons {
    /// Applies the colors to the effects' external values when they change. The weapon models get theirs when they're
    /// built (only AC TEST and sorties show them, which build them).
    pub(crate) fn update(&mut self) {
        let expansion = rows::picked_at(expansion_offset()).unwrap_or(EXPANSION_DEFAULT);
        if self.expansion != Some(expansion) {
            self.expansion = Some(expansion);
            ext_values::set_channels(&EXPANSION_CHANNELS, expansion);
            log(&format!("weapons: expansions #{expansion:06X}"));
        }
        let now = current_colors();
        if self.colors.as_ref() == Some(&now) {
            return;
        }
        let listed: Vec<String> = now.iter().map(|(model, color)| format!("{model} #{color:06X}")).collect();
        log(&format!("weapons: colors {}", listed.join(", ")));
        for (weapon, channels) in WEAPONS.iter().zip(&CHANNELS) {
            ext_values::set_channels(channels, now.get(&weapon.model).copied().unwrap_or(weapon.default));
        }
        self.colors = Some(now);
    }
}
